for i in range(12, 16):
    print(i)

'''
The range() function can also be called with three arguments. 
first = start values
second = stop values
third = step argument.
'''

for i in range (0, 33, 3):
    print(i)

# Also uses a negative number for the step argument 
# to make the for loop count down instead of up.

for i in range(5, -1, -1):
    print(i)

